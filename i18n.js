(function () {
  'use strict';

  var STORAGE_KEY = 'mixly-lang';
  var LABELS = { ru: 'RU', en: 'EN', de: 'DE' };
  var SUPPORTED = ['ru', 'en', 'de'];
  var currentLang = 'en';

  var ARTICLE_LOCALE_PATHS = [
    {
      ru: '/ru/blog/kak-pravilno-smeshivat-tabak-dlya-kalyana',
      en: '/en/blog/how-to-mix-hookah-tobacco',
      de: '/de/blog/wie-man-shisha-tabak-richtig-mischt'
    },
    {
      ru: '/ru/blog/proportsii-tabaka-dlya-kalyana',
      en: '/en/blog/hookah-tobacco-mixing-ratios',
      de: '/de/blog/shisha-tabak-mischverhaeltnisse'
    },
    {
      ru: '/ru/blog/sochetaniya-vkusov-dlya-kalyana',
      en: '/en/blog/hookah-flavor-combinations',
      de: '/de/blog/shisha-geschmackskombinationen'
    }
  ];

  function normalizePathname(pathname) {
    var path = pathname || '/';
    if (path.length > 1 && path.charAt(path.length - 1) === '/') path = path.slice(0, -1);
    if (path === '/index.html') return '/';
    return path || '/';
  }

  function localeFromPath(pathname) {
    var path = normalizePathname(pathname || location.pathname);
    var match = path.match(/^\/(ru|en|de)(?=\/|$)/);
    return match ? match[1] : null;
  }

  function pathForLocale(lang, pathname) {
    var path = normalizePathname(pathname || location.pathname);
    var hash = location.hash || '';
    var search = location.search || '';
    var i;
    var pair;
    var bare;
    var extensionless = {
      '/blog': '/blog.html',
      '/privacy': '/privacy.html',
      '/cookies': '/cookies.html',
      '/terms': '/terms.html',
      '/eula': '/eula.html',
      '/support': '/support.html'
    };
    var withHtml = {
      '/blog.html': '/blog',
      '/privacy.html': '/privacy',
      '/cookies.html': '/cookies',
      '/terms.html': '/terms',
      '/eula.html': '/eula',
      '/support.html': '/support'
    };

    for (i = 0; i < ARTICLE_LOCALE_PATHS.length; i++) {
      pair = ARTICLE_LOCALE_PATHS[i];
      if (path === pair.ru || path === pair.en || path === pair.de) {
        return (pair[lang] || pair.en) + search + hash;
      }
    }

    bare = path.replace(/^\/(ru|en|de)(?=\/|$)/, '') || '/';
    if (bare === '/index.html') bare = '/';
    if (extensionless[bare]) bare = extensionless[bare];

    if (lang === 'ru') {
      if (bare === '/') return '/' + search + hash;
      return bare + search + hash;
    }

    if (bare === '/') return '/' + lang + '/' + search + hash;
    if (withHtml[bare]) return '/' + lang + withHtml[bare] + search + hash;
    return '/' + lang + bare + search + hash;
  }

  function detectLocale() {
    var fromPath = localeFromPath(location.pathname);
    if (fromPath) return fromPath;
    try {
      var stored = localStorage.getItem(STORAGE_KEY);
      if (stored && SUPPORTED.indexOf(stored) !== -1) return stored;
    } catch (e) {}
    var candidates = [];
    try {
      if (navigator.languages && navigator.languages.length) {
        candidates = Array.prototype.slice.call(navigator.languages);
      } else if (navigator.language) {
        candidates = [navigator.language];
      }
    } catch (e2) {}
    for (var i = 0; i < candidates.length; i++) {
      var code = String(candidates[i] || '').toLowerCase();
      if (code.indexOf('ru') === 0) return 'ru';
      if (code.indexOf('de') === 0) return 'de';
    }
    return 'en';
  }

  function t(lang, key) {
    var pack = STRINGS[lang] || STRINGS.en;
    if (pack[key] != null) return pack[key];
    if (STRINGS.en[key] != null) return STRINGS.en[key];
    return '';
  }

  function applyMeta(lang) {
    var path = (location.pathname || '').split('/').pop() || 'index.html';
    if (path === '' || path === 'index.html' || path === './') {
      document.title = t(lang, 'meta.home.title');
      var desc = document.querySelector('meta[name="description"]');
      if (desc) desc.setAttribute('content', t(lang, 'meta.home.description'));
      var ogTitle = document.querySelector('meta[property="og:title"]');
      if (ogTitle) ogTitle.setAttribute('content', t(lang, 'meta.home.ogTitle'));
      var ogDesc = document.querySelector('meta[property="og:description"]');
      if (ogDesc) ogDesc.setAttribute('content', t(lang, 'meta.home.ogDescription'));
      var ld = document.querySelector('script[type="application/ld+json"]');
      if (ld) {
        try {
          var data = JSON.parse(ld.textContent);
          var description = t(lang, 'meta.home.description');
          if (Array.isArray(data['@graph'])) {
            data['@graph'].forEach(function (node) {
              if (!node || typeof node !== 'object') return;
              if (node['@type'] === 'WebSite' || node['@type'] === 'MobileApplication') {
                node.description = description;
              }
              if (node['@type'] === 'WebSite') node.inLanguage = ['ru', 'en', 'de'];
              if (node['@type'] === 'MobileApplication') node.inLanguage = lang;
            });
          } else {
            data.inLanguage = lang;
            data.description = description;
          }
          ld.textContent = JSON.stringify(data);
        } catch (e3) {}
      }
    } else if (path === 'blog.html') {
      document.title = t(lang, 'meta.blog.title');
      var blogDesc = document.querySelector('meta[name="description"]');
      if (blogDesc) blogDesc.setAttribute('content', t(lang, 'meta.blog.description'));
    } else if (path === '404.html' || path === '500.html' || path === '403.html') {
      var code = path.replace('.html', '');
      document.title = t(lang, 'meta.error.' + code + '.title');
      var errDesc = document.querySelector('meta[name="description"]');
      if (errDesc) errDesc.setAttribute('content', t(lang, 'meta.error.' + code + '.description'));
    }
  }

  var SHOT_FILES = {
    'shot.main1': 'main_1.webp',
    'shot.main2': 'main_2.webp',
    'shot.discovery': 'Discovery.png',
    'shot.lab': 'Lab.png'
  };

  function shotSrc(lang, key) {
    var file = SHOT_FILES[key];
    if (!file) return '';
    var folder = String(lang || 'en').toUpperCase();
    // Root-absolute: relative ./ breaks under /en/ and /de/ locale prefixes.
    return '/images_for_web/' + folder + '/' + file;
  }

  function applyImages(lang) {
    document.querySelectorAll('[data-i18n-src]').forEach(function (el) {
      var next = shotSrc(lang, el.getAttribute('data-i18n-src'));
      if (next && el.getAttribute('src') !== next) el.setAttribute('src', next);
    });
  }

  function applySocialLinks(lang) {
    var showThreads = lang === 'ru';
    document.querySelectorAll('[data-social-threads]').forEach(function (el) {
      el.hidden = !showThreads;
      if (showThreads) el.removeAttribute('aria-hidden');
      else el.setAttribute('aria-hidden', 'true');
    });
  }

  function applyNodes(lang) {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var value = t(lang, key);
      if (el.hasAttribute('data-i18n-html')) el.innerHTML = value;
      else el.textContent = value;
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      el.setAttribute('aria-label', t(lang, el.getAttribute('data-i18n-aria')));
    });
    document.querySelectorAll('[data-i18n-alt]').forEach(function (el) {
      el.setAttribute('alt', t(lang, el.getAttribute('data-i18n-alt')));
    });
    document.querySelectorAll('[data-i18n-href]').forEach(function (el) {
      el.setAttribute('href', t(lang, el.getAttribute('data-i18n-href')));
    });
    applyImages(lang);
    applySocialLinks(lang);
  }

  function syncSwitchers(lang) {
    document.querySelectorAll('[data-lang-switch]').forEach(function (root) {
      var toggle = root.querySelector('.lang-switch-toggle');
      if (toggle) {
        toggle.textContent = LABELS[lang] || lang.toUpperCase();
        toggle.setAttribute('aria-label', t(lang, 'lang.label') + ': ' + (LABELS[lang] || lang.toUpperCase()));
        toggle.setAttribute('aria-expanded', 'false');
      }
      root.querySelectorAll('[data-lang]').forEach(function (btn) {
        var active = btn.getAttribute('data-lang') === lang;
        btn.setAttribute('aria-checked', active ? 'true' : 'false');
        btn.tabIndex = active ? 0 : -1;
        btn.classList.toggle('is-active', active);
      });
      var menu = root.querySelector('.lang-switch-menu');
      if (menu) menu.hidden = true;
      root.classList.remove('is-open');
    });
  }

  function renderArticle(lang) {
    var metaEl = document.querySelector('#article-meta');
    var titleEl = document.querySelector('#article-title');
    var leadEl = document.querySelector('#article-lead');
    var contentEl = document.querySelector('#article-content');
    if (!metaEl || !titleEl || !leadEl || !contentEl) return;

    var slug = new URLSearchParams(location.search).get('slug') || 'base';
    var pack = (ARTICLES[lang] || ARTICLES.en || {})[slug] || (ARTICLES.en || {}).base || (ARTICLES.ru || {}).base;
    if (!pack) return;

    document.title = pack.title + ' · Mixly';
    metaEl.textContent = pack.meta;
    titleEl.textContent = pack.title;
    leadEl.textContent = pack.lead;
    contentEl.textContent = t(lang, 'article.comingSoon') || 'Coming soon';
  }

  function applyLocale(lang, persist) {
    if (SUPPORTED.indexOf(lang) === -1) lang = 'en';
    currentLang = lang;
    document.documentElement.lang = lang;
    if (persist !== false) {
      try { localStorage.setItem(STORAGE_KEY, lang); } catch (e4) {}
    }
    applyMeta(lang);
    applyNodes(lang);
    syncSwitchers(lang);
    renderArticle(lang);
    document.documentElement.classList.remove('i18n-pending');
    document.dispatchEvent(new CustomEvent('mixly:locale', { detail: { lang: lang } }));
  }

  function closeAllMenus(except, returnFocus) {
    document.querySelectorAll('[data-lang-switch]').forEach(function (root) {
      if (except && root === except) return;
      var wasOpen = root.classList.contains('is-open');
      root.classList.remove('is-open');
      var menu = root.querySelector('.lang-switch-menu');
      if (menu) menu.hidden = true;
      var toggle = root.querySelector('.lang-switch-toggle');
      if (toggle) toggle.setAttribute('aria-expanded', 'false');
      if (returnFocus && wasOpen && toggle) toggle.focus();
    });
  }

  var documentSwitchersBound = false;

  function bindSwitchers() {
    // Idempotent: SPA body swap replaces [data-lang-switch] nodes, so this must
    // be safe to call again after every page-nav navigation.
    document.querySelectorAll('[data-lang-switch]').forEach(function (root) {
      if (root.getAttribute('data-bound') === '1') return;
      root.setAttribute('data-bound', '1');
      var toggle = root.querySelector('.lang-switch-toggle');
      var menu = root.querySelector('.lang-switch-menu');
      if (toggle && menu) {
        toggle.addEventListener('click', function (event) {
          event.stopPropagation();
          var open = !root.classList.contains('is-open');
          closeAllMenus();
          if (open) {
            root.classList.add('is-open');
            menu.hidden = false;
            toggle.setAttribute('aria-expanded', 'true');
            var selected = root.querySelector('[data-lang][aria-checked="true"]');
            if (selected) selected.focus();
          }
        });
      }
      function chooseLocale(nextLang) {
        var nextPath = pathForLocale(nextLang, location.pathname);
        try { localStorage.setItem(STORAGE_KEY, nextLang); } catch (ePersist) {}
        var current = normalizePathname(location.pathname) + location.search + location.hash;
        if (current !== nextPath) {
          if (window.MixlyPageNav && typeof window.MixlyPageNav.navigate === 'function') {
            window.MixlyPageNav.navigate(new URL(nextPath, location.origin));
          } else {
            location.assign(nextPath);
          }
          return;
        }
        applyLocale(nextLang, true);
      }

      root.querySelectorAll('[data-lang]').forEach(function (btn) {
        btn.addEventListener('click', function (event) {
          event.preventDefault();
          event.stopPropagation();
          chooseLocale(btn.getAttribute('data-lang'));
          closeAllMenus();
          if (toggle) toggle.focus();
        });
      });
      root.addEventListener('keydown', function (event) {
        var buttons = Array.prototype.slice.call(root.querySelectorAll('[data-lang]'));
        var index = buttons.indexOf(document.activeElement);
        if (index === -1) return;
        var nextIndex = index;
        if (event.key === 'ArrowDown' || event.key === 'ArrowRight') nextIndex = (index + 1) % buttons.length;
        else if (event.key === 'ArrowUp' || event.key === 'ArrowLeft') nextIndex = (index - 1 + buttons.length) % buttons.length;
        else if (event.key === 'Home') nextIndex = 0;
        else if (event.key === 'End') nextIndex = buttons.length - 1;
        else return;

        event.preventDefault();
        chooseLocale(buttons[nextIndex].getAttribute('data-lang'));
        if (menu) {
          root.classList.add('is-open');
          menu.hidden = false;
          toggle.setAttribute('aria-expanded', 'true');
        }
        buttons[nextIndex].focus();
      });
    });

    if (!documentSwitchersBound) {
      documentSwitchersBound = true;
      document.addEventListener('click', function () { closeAllMenus(); });
      document.addEventListener('keydown', function (event) {
        if (event.key === 'Escape') closeAllMenus(null, true);
      });
    }
  }

  function init() {
    bindSwitchers();
    applyLocale(detectLocale(), false);
  }

  window.MixlyI18n = {
    detectLocale: detectLocale,
    applyLocale: applyLocale,
    bindSwitchers: bindSwitchers,
    pathForLocale: pathForLocale,
    localeFromPath: localeFromPath,
    renderArticle: renderArticle,
    getLang: function () { return currentLang; },
    t: function (key) { return t(currentLang, key); },
    articles: ARTICLES,
    strings: STRINGS
  };

  // Pages load this script at the end of <body>. Initialising as soon as the
  // complete document tree exists makes the first visible frame use the final
  // locale instead of painting one language and replacing it a moment later.
  if (document.body) init();
  else document.addEventListener('DOMContentLoaded', init);
})();
